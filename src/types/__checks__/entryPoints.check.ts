// ---- The guard itself must be able to fail. Every line below has to be a compile error; if one stops being
//      an error, `tsc` reports its unused @ts-expect-error.
type Run = E.RunChartFn;
type Req = Parameters<Run>[0];
type Res = ReturnType<Run>;
type Gate = Parameters<Run>[1];
export type GuardSelfTests = [
  Check<SameSignature<Run, Run>>,
  Check<SameSignature<Run & { __stub: true }, Run>>,
  Check<SameSignature<(renamed: Req, alsoRenamed?: Gate) => Res, Run>>,
  // @ts-expect-error an implementation typed `any` is not a frozen signature
  Check<SameSignature<any, Run>>,
  // @ts-expect-error neither is a function that accepts and returns anything
  Check<SameSignature<(...a: any[]) => any, Run>>,
  // @ts-expect-error a dropped optional parameter breaks the callers that pass it
  Check<SameSignature<(req: Req) => Res, Run>>,
  // @ts-expect-error an optional parameter that became required
  Check<SameSignature<(req: Req, gate: NonNullable<Gate>) => Res, Run>>,
  // @ts-expect-error an extra parameter
  Check<SameSignature<(req: Req, gate?: Gate, verbose?: boolean) => Res, Run>>,
  // @ts-expect-error a function that never returns
  Check<SameSignature<(req: Req, gate?: Gate) => never, Run>>,
  // @ts-expect-error a wider result
  Check<SameSignature<(req: Req, gate?: Gate) => Res | undefined, Run>>,
  // @ts-expect-error a narrower result
  Check<SameSignature<(req: Req, gate?: Gate) => Promise<Awaited<Res> & { extra: number }>, Run>>,
  // @ts-expect-error a narrower property inside the result
  Check<SameSignature<() => { status: 'saved'; flush(): Promise<void> }, E.UseAutosaveFn>>,
  // @ts-expect-error a value that is not a function
  Check<SameSignature<{ __stub: true }, Run>>,
  // @ts-expect-error a component with other props
  Check<SameProps<ComponentType<{ doc: string }>, U.PatternViewProps>>,
  // @ts-expect-error a component typed `any`
  Check<SameProps<any, U.PatternViewProps>>,
  // @ts-expect-error a component with one prop missing
  Check<SameProps<(props: Omit<U.PatternViewProps, 'highlight'>) => null, U.PatternViewProps>>,
  Check<SameProps<(props: U.PatternViewProps) => null, U.PatternViewProps>>,
  Check<SameProps<ComponentType<U.MaterialsViewProps>, U.MaterialsViewProps>>,
];
