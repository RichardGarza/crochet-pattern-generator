// Compile-time guard for the frozen signatures of DESIGN.md §5.2.1. Step 0 owned; no runtime code.
//
// Each line asserts that the function (or component) a module exports today has EXACTLY the frozen signature:
// identical parameter types (their names are free) and an identical result type. A Step 0 stub passes, and so
// does a real implementation written with the same types. An implementation that dropped an optional
// parameter, widened or narrowed a type, or is typed `any` makes `npm run typecheck` fail HERE — fix the
// implementation, or propose the change through the S0 amendment lane (§6.1 rule 7). Do not edit this file to
// make a track compile.
//
// `typeof import(…)` is a type query: nothing is imported at run time.
import type { ComponentType } from 'react';
import type * as E from '../entryPoints';
import type * as U from '../ui';

type Identical<A, B> = (<T>() => T extends A ? 1 : 2) extends (<T>() => T extends B ? 1 : 2) ? true : false;
type IsAny<T> = 0 extends 1 & T ? true : false;
type Fn = (...a: never[]) => unknown;

/** True when `Actual` is a function with the frozen parameter list and the frozen result type. */
type SameSignature<Actual, Frozen extends Fn> =
  IsAny<Actual> extends true
    ? false
    : Actual extends Fn
      ? Identical<Parameters<Actual>, Parameters<Frozen>> extends true
        ? Identical<ReturnType<Actual>, ReturnType<Frozen>>
        : false
      : false;

/** The props of a function, class, memo, forwardRef or lazy component. */
type PropsOf<C> = C extends (props: infer P) => unknown ? P : C extends new (props: infer P, ...rest: never[]) => unknown ? P : never;

/** True when `Actual` is a React component whose props are exactly `Props`. */
type SameProps<Actual, Props> = IsAny<Actual> extends true ? false : Identical<PropsOf<Actual>, Props>;

type Check<T extends true> = T;

// ---- Step 0 kernels. encodePng returns Uint8Array<ArrayBuffer>, a subtype of the frozen Uint8Array that can
//      also be handed to Blob and crypto.subtle; so its result is checked for assignability, not identity.
